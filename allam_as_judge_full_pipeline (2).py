# Extract the core text from the claim column (remove extra metadata)
def clean_claim(claim_text):
    """Extract just the text from the statement"""
    parts = str(claim_text).split()
    # Take the part of the text after the technical metadata
    if len(parts) > 4:
        return ' '.join(parts[4:])
    return claim_text

