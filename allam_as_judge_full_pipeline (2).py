# ===== Step 1: Paths - adjust these =====
BASE_MODEL_PATH = "/content/drive/MyDrive/GP/models/ALLaM-7B"  # the base model
FINE_TUNED_PATH = "/content/drive/MyDrive/GP/fine_tuned_model_few_shot2/final_model"  # the model after FT
TEST_DATA_PATH = "/content/drive/MyDrive/GP/ALLaM_results/original_test_set.csv"  # test data
RESULTS_PATH = "/content/drive/MyDrive/GP/ALLaM_results/exp4_after_fine.csv"  # results

SAVE_EVERY = 20

# ===== Step 2: Load the fine-tuned model =====
print("\n⏳ Loading the fine-tuned model...\n")

# Load the base model
base_model = AutoModelForCausalLM.from_pretrained(
    BASE_MODEL_PATH,
    trust_remote_code=True,
    device_map="auto",
    torch_dtype=torch.float16,
)

# Load the LoRA adapters (the fine-tuned model)
model = PeftModel.from_pretrained(
    base_model,
    FINE_TUNED_PATH,
    is_trainable=False
)

# Load the tokenizer
tokenizer = AutoTokenizer.from_pretrained(
    FINE_TUNED_PATH,
    trust_remote_code=True
)

print("✅ Fine-tuned model loaded successfully!")
print(f"📍 Model is on: {next(model.parameters()).device}\n")

# ===== Step 3: Load the test data =====
print("📂 Loading the test set...")
test_df = pd.read_csv(TEST_DATA_PATH)
print(f"✅ Loaded {len(test_df)} examples from the test set\n")

# ===== Step 4: Few-shot CoT prompt (same as training!) =====

def judge_claim(claim):
    prompt = f"""
احكم على العبارة التالية بإجابة واحدة من دون تبرير:
"{claim}"
هل العبارة صحيحة أم خاطئة؟
"""
    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    outputs = model.generate(**inputs, max_new_tokens=10, do_sample=False,temperature=0.0)
    return tokenizer.decode(outputs[0], skip_special_tokens=True)

# ===== Step 5: Resume from the last checkpoint =====
if os.path.exists(RESULTS_PATH):
    df_old = pd.read_csv(RESULTS_PATH)
    results = df_old.to_dict("records")
    start_from = len(results)
    print(f"🔁 Resuming from row {start_from}")
else:
    results = []
    start_from = 0
    print("🟢 Starting fresh")

total = len(test_df)
print(f"\n📊 Statistics:")
print(f"   • Total test set: {total}")
print(f"   • Already processed: {start_from}")
print(f"   • Remaining: {total - start_from}")
print(f"   • Estimated time: ~{(total - start_from) * 3 / 60:.0f} minutes\n")

# ===== Step 6: Evaluation mode =====
model.eval()

# ===== Step 7: Processing =====
print("⏳ Evaluating on the test set...\n")

for i in tqdm(range(start_from, total), desc="Evaluating", initial=start_from, total=total):
    claim = str(test_df.iloc[i]['claim'])

    try:
        judgment = judge_claim(claim)
    except Exception as e:
        judgment = f"ERROR: {type(e).__name__}: {str(e)}"

    results.append({
        "claim": claim,
        "ground_truth": test_df.iloc[i]['binary_label'],
        "model_judgment": judgment
    })

    # Periodic save
    if (i + 1) % SAVE_EVERY == 0:
        pd.DataFrame(results).to_csv(RESULTS_PATH, index=False)
        print(f"💾 Saved at {i+1}/{total}")
# ===== Step 8: Final save =====
pd.DataFrame(results).to_csv(RESULTS_PATH, index=False)

print(f"\n✅ Evaluation finished!")
print(f"💾 Results saved to:\n   {RESULTS_PATH}")

